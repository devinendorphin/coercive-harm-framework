"""Render the arithmetic appendix from summary.json, with no recoding or new estimates.

python3 -I render_whole_story_tables.py RESULTS_DIR
"""
import json
import sys
from pathlib import Path

D=Path(sys.argv[1]);s=json.loads((D/'summary.json').read_text());lines=[]
def out(x=''):lines.append(x)
def pct(x):return 'unavailable' if x is None else f'{100*x:.1f}%'
def number(q,interval=True):
    text=f"{q['k']}/{q['n']} ({pct(q['rate'])})"
    if interval and q['n']:
        text+=f" [{pct(q['ci95'][0])}–{pct(q['ci95'][1])}]"
    return text

def table(headers,rows):
    out('| '+' | '.join(headers)+' |');out('|'+'|'.join(['---']*len(headers))+'|')
    for row in rows:out('| '+' | '.join(map(str,row))+' |')
    out()

names={'W1':'Fully protected among those reaching an institution [W1]',
       'W2':'Disbelief, blame, dismissal or self-protection [W2]',
       'W3':'Decisive work outside the institution, any protection [W3]',
       'W3_protected_only':'Decisive work outside the institution, full protection only',
       'never_reached':'Never reached, among known and agreed reached status',
       'harmed_ever':'Institutional harm at any point, among those who reached'}
short={'W1':'Full protection','W2':'Adverse response','W3':'Outside work','never_reached':'Never reached'}
out('# Whole-story arithmetic appendix — 2026-11-11');out()
out('Generated by `tools/render_whole_story_tables.py` from `summary.json`. Read `RESULTS.md` and '
    '`QUOTATION-AUDIT.md` for interpretation and disconfirming checks. Every Claude figure is '
    '**unblinded**; Codex figures are **blinded**. All-seasons figures mix both. '
    'S17 occurs once in each pooled analysis. Left/right means A/B for Claude and CA/CB for Codex; '
    'pooled columns follow the assigned family in each season.');out()
out('Brackets after a rate give its Wilson 95% interval. These describe the coded sample, '
    'do not account for shared seasons, and are not population estimates. A zero denominator is '
    'unavailable. “Omitted” means one or both coders did not meet eligibility; “disagreed” means '
    'both were eligible but differed on the indicator. The primary analysis retains one person–harm '
    'story per season. Unique analyses retain the earliest identifiable appearance before eligibility, '
    'agreement and exclusions. Separate harms remain separate.');out()
for group,g in s['groups'].items():
    out('## '+group+' — '+g['label']);out()
    out('Seasons: '+', '.join(map(str,g['seasons']))+'.');out()
    primary=g['variants']['season_unchanged']
    out('### Primary figures and each coder’s own figures');out()
    table(['Measure','Agreed, with 95% interval','Disagreed','Omitted','Left own, with 95% interval','Right own, with 95% interval'],[
        [names[m],number(primary['headline'][m]),primary['headline'][m]['disagreed'],primary['headline'][m]['omitted'],
         number(primary['own']['left'][m]),number(primary['own']['right'][m])] for m in names])
    table(['Prediction','Threshold','Claude band','Codex band','Band used','Distance','Decision'],[
        [m,pct(dec['threshold']),pct(s['framing']['claude']['variants']['season_unchanged']['band'][m]),
         pct(s['framing']['codex']['variants']['season_unchanged']['band'][m]),pct(dec['band']),pct(dec['distance']),dec['verdict']]
        for m,dec in primary['decision'].items()])
    table(['Coder stream','Records','Unknown reached status','Protected/partly protected, unknown decisive worker'],[
        [c,ev['people'],ev['unknown_reached'],ev['protected_unknown_worker']] for c,ev in primary['own'].items()])
    out('### Sensitivities');out()
    out('Each cell is numerator/denominator, rate and 95% interval. Every sensitivity is beside '
        'the unchanged primary result; none replaces it. The JSON also contains each sensitivity’s '
        'own-coder, central-only, agreement and reasons figures.');out()
    table(['Variant',*short.values()],[[v]+[number(ev['headline'][m]) for m in short] for v,ev in g['variants'].items()])
    table(['Variant','W1 decision','W2 decision','W3 decision'],[[v]+[ev['decision'][m]['verdict'] for m in ['W1','W2','W3']]
          for v,ev in g['variants'].items()])
    out('### Central survivors only');out()
    central=primary['central_only']
    table(['Measure','Agreed, 95% interval','Left own, 95% interval','Right own, 95% interval'],[
        [names[m],number(central['agreed'][m]),number(central['own']['left'][m]),number(central['own']['right'][m])] for m in names])
    out('### Agreement');out()
    table(['Field','Pairs with both values','Percent agreement','Chance-adjusted agreement (Cohen’s kappa)'],[
        [field,q['n'],pct(q['pct_agree']),'undefined' if q['kappa'] is None else f"{q['kappa']:.3f}"]
        for field,q in primary['agreement'].items() if 'pct_agree' in q])
    finding=primary['agreement']['person_finding']
    out('People found by both / found by either: '+number(finding,False)+'. '
        f"Own records: {finding['left_total']} left; {finding['right_total']} right.");out()
    table(['Coder stream','Contacts recorded','Contacts per own record'],[
        [c,q['total'],f"{q['per_person']:.2f}"] for c,q in primary['agreement']['contacts'].items()])
    out('### Reasons recorded for never reaching');out()
    reasons=primary['never_reached_reasons']
    keys=sorted(set(reasons['left'])|set(reasons['right'])|set(reasons['both']))
    table(['Reason','Left own count','Right own count','Both on the same matched story'],[
        [k,reasons['left'].get(k,0),reasons['right'].get(k,0),reasons['both'].get(k,0)] for k in keys])
    out('Multiple reasons may apply to one story; these counts are not added together.');out()
    if group=='all_codex17':continue
    out('### Season figures');out()
    out('Cells give agreed / left-own / right-own fractions and rates. All intervals and omissions '
        'for these season figures are in `summary.json`.');out()
    table(['Season','Coder family / exposure','Matched','Full protection: agreed; left; right','Adverse response: agreed; left; right',
           'Outside work: agreed; left; right','Never reached: agreed; left; right'],[
        [season,ev['label'],ev['matched']]+['; '.join([number(ev['headline'][m],False),number(ev['own']['left'][m],False),number(ev['own']['right'][m],False)])
                                          for m in short] for season,ev in g['by_season'].items()])
    out('### Season agreement');out()
    fields=['reached','outcome','W2_indicator','W3_indicator','harmed_ever','account_alone']
    out('Field cells give percent agreement / kappa / pairs with both values. Undefined kappa '
        'means the chance-agreement denominator was zero, not perfect validity.');out()
    def agr(q):return f"{pct(q['pct_agree'])} / {q['kappa']:.3f} / {q['n']}" if q['kappa'] is not None else f"{pct(q['pct_agree'])} / undefined / {q['n']}"
    table(['Season','Coder family / exposure','Person finding',*fields,'Contacts left / right'],[
        [season,ev['label'],number(ev['agreement']['person_finding'],False)]+[agr(ev['agreement'][f]) for f in fields]+
        [str(ev['agreement']['contacts']['left']['total'])+' / '+str(ev['agreement']['contacts']['right']['total'])]
        for season,ev in g['by_season'].items()])
out('## S17 cross-check — Claude unblinded versus Codex blinded');out()
out('A and B are Claude unblinded; CA and CB are Codex blinded. Exposure and model family '
    'are confounded. Four cross-family comparisons are all shown, alongside both within-family pairs.');out()
out('Signed differences below are Claude **unblinded** minus Codex **blinded** on S17, in '
    'percentage points. Coverage and eligible sets differ; these are not causal exposure effects.');out()
table(['Stream',*short.values()],[[stream]+[pct(q[m]) for m in short]
      for stream,q in s['s17_family_differences'].items()])
for label,ev in s['s17_crosscheck'].items():
    out('### '+label);out()
    table(['Measure','Agreed, 95% interval','Left own, 95% interval','Right own, 95% interval'],[
        [names[m],number(ev['headline'][m]),number(ev['own']['left'][m]),number(ev['own']['right'][m])] for m in names])
    table(['Field','Percent agreement','Kappa','Pairs with both values'],[
        [f,pct(q['pct_agree']),'undefined' if q['kappa'] is None else f"{q['kappa']:.3f}",q['n']]
        for f,q in ev['agreement'].items() if 'pct_agree' in q])
    out('Person finding: '+number(ev['agreement']['person_finding'],False)+'.');out()
out('## Framing checks');out()
for family,fr in s['framing'].items():
    out('### '+fr['label']);out()
    out('Seasons: '+', '.join(map(str,fr['seasons']))+'. The A/B neutral comparison on Codex’s '
        'S13 framing season is Claude **unblinded**, because no Codex neutral S13 pair exists.');out()
    v=fr['variants']['season_unchanged']
    table(['Coder',*short.values()],[[c]+[number(ev[m]) for m in short] for c,ev in v['own'].items()])
    table(['Variant',*short.values()],[[variant]+[pct(ev['band'][m]) for m in short] for variant,ev in fr['variants'].items()])
out('## Quotation checks and input flags');out()
out('The match test checks wording against transcripts, not code validity or the truth of an '
    'account. Too-short quotations are outside the script’s tested denominator and flagged separately.');out()
if not s['quotation_checks']:out('PENDING: quotation checks have not been supplied.');out()
else:
    table(['Coder','Quotations found / tested','Too short','Found elsewhere in season/unassigned pool','Person records flagged'],[
        [coder,f"{q['found']}/{q['tested']}",q['too_short'],q['other_episode'],q['person_records_flagged']]
        for coder,q in s['quotation_totals_by_coder'].items()])
    table(['File','Found / tested','Too short','Other episode'],[
        [stem,f"{q['found']}/{q['tested']}",q['too_short'],q['other_episode']]
        for stem,q in s['quotation_checks'].items()])
for label,files in s['flags']['by_file'].items():
    out(label+': '+(', '.join(f'{stem}: {n}' for stem,n in files.items()) or 'none')+'.');out()
out('Person IDs and exact flags are in `flags.csv`; no coder output was changed.');out()
out('Reading-log comparison with the original committed chunk counts: '
    f"{s['reading_log_totals']['entries']} entries in {s['reading_log_totals']['files']} coder files; "
    f"{s['reading_log_totals']['files_with_issues']} files with discrepancies. "
    'This checks the reported reading endpoints, not the coder’s comprehension. '
    'Transcript rebuild and current-file checks are documented in `QUOTATION-AUDIT.md`.');out()
out('## Other people mentioned without a followed story');out()
out('Entries and stated numeric subtotals can overlap within or across seasons and with named '
    'stories. Unknown counts, approximations and ranges are retained exactly in `others_mentioned.json`; '
    'they are not coerced to zero or combined into a unique-person total. An entry is not evidence '
    'that its people never contacted an institution. The collection marks who was not followed '
    'individually by this coding.');out()
table(['File / coder','Mention entries','Entries with a numeric count','Numeric subtotal, with overlap'],[
    [stem,q['entries'],q['numeric_entries'],q['numeric_subtotal_with_overlap']] for stem,q in s['others_mentioned'].items()])
(D/'ARITHMETIC.md').write_text('\n'.join(lines)+'\n')
print('Rendered ARITHMETIC.md')
